---@diagnostic disable: undefined-global
-- The workspace language server is set up for WoW addons, which have no io or os; this is a plain Lua tool.
-- Builds AnglersCompanion/Data/ErrorStrings.lua: the game's own cast and fishing error texts in every addon language.
--
-- Usage (from the repository root, Lua 5.1, needs curl):
--   lua tools/build-error-strings.lua
--
-- Texts come from the client's GlobalStrings table on wago.tools. The Forever build has no Italian texts,
-- so Italian is taken from the current retail build.

local ROOT = (arg[0]:match("^(.*)/tools/[^/]+$") or ".")
local OUTPUT = ROOT .. "/AnglersCompanion/Data/ErrorStrings.lua"
local BUILD = "1.60.1.70888"
local URL = "https://wago.tools/db2/GlobalStrings/csv?locale=%s"

-- Same order as ns.LANGUAGES in Locales.lua.
local LOCALES = {
    { code = "enUS", build = BUILD },
    { code = "esES", build = BUILD },
    { code = "deDE", build = BUILD },
    { code = "frFR", build = BUILD },
    { code = "ptBR", build = BUILD },
    { code = "itIT" },
}

local function Wanted(tag)
    return tag:match("^SPELL_FAILED_") or tag:match("^ERR_FISH_") or tag == "ERR_INV_FULL"
end

local function Fail(message)
    io.stderr:write("error: " .. message .. "\n")
    os.exit(1)
end

local function Fetch(url)
    local pipe = io.popen("curl -sfL " .. ("%q"):format(url))
    local data = pipe:read("*a")
    local ok = pipe:close()
    if not ok or data == "" then Fail("could not download " .. url) end
    return data
end

local function ParseCSV(text)
    local rows, row, field = {}, {}, {}
    local i, n, quoted = 1, #text, false
    while i <= n do
        local c = text:sub(i, i)
        if quoted then
            if c == '"' then
                if text:sub(i + 1, i + 1) == '"' then
                    field[#field + 1] = '"'
                    i = i + 1
                else
                    quoted = false
                end
            else
                field[#field + 1] = c
            end
        elseif c == '"' then
            quoted = true
        elseif c == "," then
            row[#row + 1] = table.concat(field)
            field = {}
        elseif c == "\n" or c == "\r" then
            if c == "\r" and text:sub(i + 1, i + 1) == "\n" then i = i + 1 end
            row[#row + 1] = table.concat(field)
            rows[#rows + 1] = row
            row, field = {}, {}
        else
            field[#field + 1] = c
        end
        i = i + 1
    end
    if #field > 0 or #row > 0 then
        row[#row + 1] = table.concat(field)
        rows[#rows + 1] = row
    end
    return rows
end

local function Load(locale)
    local url = URL:format(locale.code) .. (locale.build and "&build=" .. locale.build or "")
    local rows = ParseCSV(Fetch(url))
    local tagColumn, textColumn
    for i, name in ipairs(rows[1] or {}) do
        if name == "BaseTag" then tagColumn = i elseif name == "TagText_lang" then textColumn = i end
    end
    if not tagColumn or not textColumn then Fail("unexpected columns in " .. url) end
    local texts = {}
    for i = 2, #rows do
        local tag, text = rows[i][tagColumn], rows[i][textColumn]
        if tag and text and text ~= "" and Wanted(tag) then texts[tag] = text end
    end
    return texts
end

local byLocale = {}
for i, locale in ipairs(LOCALES) do
    print("Downloading " .. locale.code)
    byLocale[i] = Load(locale)
end

local tags = {}
for tag in pairs(byLocale[1]) do tags[#tags + 1] = tag end
table.sort(tags)

local out = {
    "local _, ns = ...",
    "",
    "-- Generated by tools/build-error-strings.lua from the game's GlobalStrings. Rebuild it instead of editing by hand.",
    "-- Each error is { enUS, esES, deDE, frFR, ptBR, itIT }, in the order of ns.LANGUAGES.",
    "ns.ERROR_STRINGS = {",
}
local missing = 0
for _, tag in ipairs(tags) do
    local english = byLocale[1][tag]
    local texts = {}
    for i = 1, #LOCALES do
        local text = byLocale[i][tag]
        if not text then
            text = english
            missing = missing + 1
        end
        texts[i] = ("%q"):format(text):gsub("\\\n", "\\n")
    end
    out[#out + 1] = ("    %s = { %s },"):format(tag, table.concat(texts, ", "))
end
out[#out + 1] = "}"

local file = assert(io.open(OUTPUT, "wb"))
file:write(table.concat(out, "\n"), "\n")
file:close()
print(("Wrote %d errors to %s (%d missing translations fall back to English)"):format(#tags, OUTPUT, missing))
