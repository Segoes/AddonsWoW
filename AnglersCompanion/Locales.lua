ns.DEFAULT_LANGUAGE = "enUS"

function ns.GetLanguage()
    local code = AnglersCompanionDB and AnglersCompanionDB.language
    return ns.STRINGS[code] and code or ns.DEFAULT_LANGUAGE
end

function ns.LanguageIndex()
    local code = ns.GetLanguage()
    for i, language in ipairs(ns.LANGUAGES) do
        if language.code == code then return i end
    end
    return 1
end

function ns.LanguageInfo(code)
    for _, language in ipairs(ns.LANGUAGES) do
        if language.code == code then return language end
    end
end

function ns.LanguageByShort(short)
    for _, language in ipairs(ns.LANGUAGES) do
        if strlower(language.short) == strlower(short) then return language end
    end
end

function ns.LanguageShortList()
    local list = {}
    for _, language in ipairs(ns.LANGUAGES) do
        list[#list + 1] = strlower(language.short)
    end
    return table.concat(list, "|")
end

function ns.L(key)
    return ns.STRINGS[ns.GetLanguage()][key] or ns.STRINGS[ns.DEFAULT_LANGUAGE][key] or key
end
